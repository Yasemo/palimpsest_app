import { api } from '../api.js';
import { showLoading, hideLoading, showNotification } from '../router.js';

let availableModels = [];

export async function renderAI() {
  const container = document.getElementById('app-content');
  
  container.innerHTML = `
    <div class="page-header">
      <h2>AI Configuration</h2>
      <p>Configure AI model and system prompt</p>
    </div>
    <div id="ai-config" class="ai-config">
      <div class="loading-text">Loading AI configuration...</div>
    </div>
  `;

  await loadAIConfig();
}

async function loadAIConfig() {
  try {
    showLoading();
    const [config, models] = await Promise.all([
      api.getAIConfig(),
      api.getAIModels()
    ]);
    availableModels = models;
    hideLoading();

    const container = document.getElementById('ai-config');
    container.innerHTML = `
      <div class="config-form">
        <div class="form-group">
          <label for="ai-model">Model</label>
          <div class="model-selector-wrapper">
            <div class="model-selector-display" id="model-selector-display">
              <div class="selected-model-info">
                <span class="model-name">Loading...</span>
              </div>
              <i data-feather="chevron-down"></i>
            </div>
            <input type="hidden" id="ai-model" value="${config.model}" />
          </div>
          <small>Click to browse and select from available OpenRouter models</small>
        </div>

        <div class="form-group">
          <label for="ai-temperature">Temperature</label>
          <input type="number" id="ai-temperature" value="${config.temperature}" step="0.1" min="0" max="2" />
          <small>Controls randomness (0.0 - 2.0)</small>
        </div>

        <div class="form-group">
          <label for="ai-system-prompt">System Prompt</label>
          <textarea id="ai-system-prompt" rows="6">${config.system_prompt || ''}</textarea>
          <small>Instructions for AI behavior</small>
        </div>

        <button class="btn-primary" onclick="window.saveAIConfig()">Save Configuration</button>
      </div>

      <div class="info-box">
        <h3>About AI Configuration</h3>
        <p>The AI processes info packages generated by queries and creates content based on your system prompt and directive.</p>
        <p>Select a model from the dropdown above to see pricing, context window, and other specifications.</p>
      </div>
    `;

    // Initialize the model selector display
    updateSelectedModelDisplay(config.model);
    
    // Add click handler to open model selector modal
    document.getElementById('model-selector-display').addEventListener('click', () => {
      showModelSelectorModal(config.model);
    });

    // Initialize feather icons
    if (window.feather) feather.replace();
  } catch (error) {
    hideLoading();
    showNotification('Failed to load AI config: ' + error.message, 'error');
  }
}

function updateSelectedModelDisplay(modelId) {
  const displayElement = document.getElementById('model-selector-display');
  if (!displayElement) return;

  const model = availableModels.find(m => m.id === modelId);
  
  if (model) {
    const promptCost = formatCost(model.pricing?.prompt);
    const completionCost = formatCost(model.pricing?.completion);
    
    displayElement.querySelector('.selected-model-info').innerHTML = `
      <div>
        <span class="model-name">${escapeHtml(model.name || model.id)}</span>
        <span class="model-id">${escapeHtml(model.id)}</span>
      </div>
      <div class="model-pricing">
        <span class="cost-label">In: ${promptCost}</span>
        <span class="cost-label">Out: ${completionCost}</span>
      </div>
    `;
  } else {
    displayElement.querySelector('.selected-model-info').innerHTML = `
      <span class="model-name">${escapeHtml(modelId || 'Select a model')}</span>
    `;
  }
}

function showModelSelectorModal(currentModelId) {
  // Group models by provider
  const modelsByProvider = {};
  availableModels.forEach(model => {
    const provider = model.id.split('/')[0] || 'Other';
    if (!modelsByProvider[provider]) {
      modelsByProvider[provider] = [];
    }
    modelsByProvider[provider].push(model);
  });

  // Create modal overlay
  const modalOverlay = document.createElement('div');
  modalOverlay.className = 'modal-overlay model-selector-modal modal-visible';
  modalOverlay.innerHTML = `
    <div class="modal-content modal-large">
      <div class="modal-header">
        <h3>Select AI Model</h3>
        <button class="modal-close" onclick="this.closest('.modal-overlay').remove()">
          <i data-feather="x"></i>
        </button>
      </div>
      <div class="modal-body">
        <div class="model-search-bar">
          <input 
            type="text" 
            id="model-search" 
            class="form-control" 
            placeholder="Search models by name, provider, or capabilities..."
          />
        </div>
        <div class="models-list" id="models-list">
          ${Object.keys(modelsByProvider).sort().map(provider => `
            <div class="provider-group" data-provider="${escapeHtml(provider)}">
              <h4 class="provider-name">${escapeHtml(provider)}</h4>
              <div class="provider-models">
                ${modelsByProvider[provider].map(model => {
                  const isSelected = model.id === currentModelId;
                  const promptCost = formatCost(model.pricing?.prompt);
                  const completionCost = formatCost(model.pricing?.completion);
                  const contextLength = model.context_length ? formatNumber(model.context_length) : 'N/A';
                  
                  return `
                    <div class="model-card ${isSelected ? 'selected' : ''}" data-model-id="${escapeHtml(model.id)}" data-model-name="${escapeHtml(model.name || model.id)}">
                      <div class="model-card-header">
                        <div class="model-card-title">
                          <span class="model-card-name">${escapeHtml(model.name || model.id)}</span>
                          ${isSelected ? '<span class="selected-badge">Current</span>' : ''}
                        </div>
                        <div class="model-card-id">${escapeHtml(model.id)}</div>
                      </div>
                      <div class="model-card-body">
                        ${model.description ? `<p class="model-description">${escapeHtml(model.description).substring(0, 150)}${model.description.length > 150 ? '...' : ''}</p>` : ''}
                        <div class="model-specs">
                          <div class="spec-item">
                            <span class="spec-label">Context:</span>
                            <span class="spec-value">${contextLength} tokens</span>
                          </div>
                          <div class="spec-item">
                            <span class="spec-label">Input:</span>
                            <span class="spec-value">${promptCost}</span>
                          </div>
                          <div class="spec-item">
                            <span class="spec-label">Output:</span>
                            <span class="spec-value">${completionCost}</span>
                          </div>
                        </div>
                      </div>
                      <div class="model-card-footer">
                        <button class="btn-sm btn-primary select-model-btn" data-model-id="${escapeHtml(model.id)}">
                          ${isSelected ? 'Selected' : 'Select'}
                        </button>
                      </div>
                    </div>
                  `;
                }).join('')}
              </div>
            </div>
          `).join('')}
        </div>
      </div>
    </div>
  `;

  document.body.appendChild(modalOverlay);

  // Trigger animation after DOM insertion
  setTimeout(() => {
    modalOverlay.classList.add('modal-visible');
  }, 10);

  // Initialize feather icons
  if (window.feather) feather.replace();

  // Add search functionality
  const searchInput = document.getElementById('model-search');
  searchInput.addEventListener('input', (e) => {
    const searchTerm = e.target.value.toLowerCase();
    const modelCards = document.querySelectorAll('.model-card');
    const providerGroups = document.querySelectorAll('.provider-group');

    modelCards.forEach(card => {
      const modelId = card.dataset.modelId.toLowerCase();
      const modelName = card.dataset.modelName.toLowerCase();
      const provider = card.closest('.provider-group').dataset.provider.toLowerCase();
      
      const matches = modelId.includes(searchTerm) || 
                      modelName.includes(searchTerm) || 
                      provider.includes(searchTerm);
      
      card.style.display = matches ? 'block' : 'none';
    });

    // Hide provider groups with no visible models
    providerGroups.forEach(group => {
      const visibleModels = group.querySelectorAll('.model-card[style="display: block;"], .model-card:not([style*="display: none"])');
      group.style.display = visibleModels.length > 0 ? 'block' : 'none';
    });
  });

  // Add click handlers for model selection
  modalOverlay.querySelectorAll('.select-model-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const modelId = btn.dataset.modelId;
      selectModel(modelId);
      modalOverlay.remove();
    });
  });

  // Close on backdrop click
  modalOverlay.addEventListener('click', (e) => {
    if (e.target === modalOverlay) {
      modalOverlay.remove();
    }
  });
}

function selectModel(modelId) {
  const hiddenInput = document.getElementById('ai-model');
  if (hiddenInput) {
    hiddenInput.value = modelId;
    updateSelectedModelDisplay(modelId);
  }
}

function formatCost(cost) {
  if (!cost) return 'N/A';
  
  // Convert to cost per 1M tokens
  const costPerMillion = parseFloat(cost) * 1000000;
  
  if (costPerMillion < 0.01) {
    return 'Free';
  } else if (costPerMillion < 1) {
    return `$${costPerMillion.toFixed(3)}/1M`;
  } else {
    return `$${costPerMillion.toFixed(2)}/1M`;
  }
}

function formatNumber(num) {
  if (!num) return '0';
  return num.toLocaleString();
}

function escapeHtml(text) {
  if (!text) return '';
  const div = document.createElement('div');
  div.textContent = text;
  return div.innerHTML;
}

window.saveAIConfig = async () => {
  const model = document.getElementById('ai-model').value;
  const temperature = parseFloat(document.getElementById('ai-temperature').value);
  const system_prompt = document.getElementById('ai-system-prompt').value;

  try {
    showLoading();
    await api.updateAIConfig({ model, temperature, system_prompt });
    hideLoading();
    showNotification('AI configuration saved successfully', 'success');
  } catch (error) {
    hideLoading();
    showNotification('Failed to save AI config: ' + error.message, 'error');
  }
};
